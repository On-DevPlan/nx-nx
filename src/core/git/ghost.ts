// 幽灵镜像：把历史重写成「只剩 rewrite.txt」的镜像。
//
// 契约（来自 gitlike 的 cleanup-history）：
//   **不修改** 标题 / 作者 / 邮箱 / 日期 / 拓扑；
//   **修改**   每个 commit 的文件树只剩一个 rewrite.txt，内容是原始提交的元数据；
//   **追加**   末尾 2 个 commit：删掉 rewrite.txt + 注入当前工作区快照。
//
// 危险的不可逆操作，所以：
//   - 执行前必须先备份 .git 目录（backupGitDir）；
//   - 每阶段失败都要把备份路径告诉用户（由调用方负责输出）。
import { cpSync, existsSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { runGit } from './exec.js';
import { commitsBetween, type CommitMeta } from './commits.js';
import { gitDir } from './repo.js';

export const GHOST_REWRITE_FILE = 'rewrite.txt';
export const GHOST_REWRITE_HEADER =
  '# rewrite history snapshot, generated by nx-nx git cleanup-history\n';
export const GHOST_FINAL_SNAPSHOT_MESSAGE = 'chore: restore working snapshot via cleanup-history';
export const GHOST_REMOVE_FILE_MESSAGE = 'chore: remove rewrite placeholder';

/** 环境变量前缀——刻意不叫 GITLIKE_*，避免与旧的 gitlike 工具互相干扰。 */
const ENV_META = 'NX_GIT_GHOST_META';
const ENV_HEADER = 'NX_GIT_GHOST_HEADER';

/**
 * tree-filter 脚本：把工作树清空，只留 rewrite.txt。
 *
 * 脚本内容内嵌在代码里（不随包发 .sh——仓库 .gitignore 通常会排掉它），
 * 运行时落临时文件再用 bash 执行；路径转 POSIX 以免 Git for Windows 的 bash
 * 被反斜杠绊住。
 */
const GHOST_TREE_FILTER = `#!/bin/bash
# nx-nx git ghost-rewrite tree-filter
set -e
row=""
if [ -n "$NX_GIT_GHOST_META" ] && [ -f "$NX_GIT_GHOST_META" ]; then
    row=$(awk -F'\\t' -v c="$GIT_COMMIT" '$1 == c {print; exit}' "$NX_GIT_GHOST_META" || true)
fi

# 清空工作树，但保留 filter-branch 自己建的 .git-rewrite 与 .git
find . -mindepth 1 -maxdepth 1 \\
    ! -name '.git-rewrite' \\
    ! -name '.git' \\
    -exec rm -rf {} + 2>/dev/null || true

if [ -n "$row" ]; then
    hash=$(echo "$row" | awk -F'\\t' '{print $1}')
    date=$(echo "$row" | awk -F'\\t' '{print $2}')
    author=$(echo "$row" | awk -F'\\t' '{print $3}')
    email=$(echo "$row" | awk -F'\\t' '{print $4}')
    files=$(echo "$row" | awk -F'\\t' '{print $5}')
    {
        printf '%s' "$NX_GIT_GHOST_HEADER"
        printf '%s | %s | %s <%s> | files=%s\\n' "$hash" "$date" "$author" "$email" "$files"
    } > ${GHOST_REWRITE_FILE}
else
    short_hash=$(echo "$GIT_COMMIT" | cut -c1-12)
    {
        printf '%s' "$NX_GIT_GHOST_HEADER"
        printf 'commit: %s\\n' "$short_hash"
    } > ${GHOST_REWRITE_FILE}
fi
git add -A . 2>/dev/null || git add ${GHOST_REWRITE_FILE}
exit 0
`;

/** 把提交元数据写成 TSV，供 tree-filter 脚本按 commit 查表。 */
function writeGhostMetadata(rows: CommitMeta[]): string {
  const dir = mkdtempSync(join(tmpdir(), 'nx-nx-ghost-meta-'));
  const file = join(dir, 'meta.tsv');
  const body = rows
    .map((r) => `${r.hash}\t${r.date}\t${r.author}\t${r.email}\t${r.files}`)
    .join('\n');
  writeFileSync(file, body ? `${body}\n` : '', 'utf8');
  return file;
}

/** 备份 .git 目录，返回备份目录路径。 */
export async function backupGitDir(cwd?: string): Promise<string> {
  const abs = await gitDir(cwd);
  const stamp = new Date().toISOString().replace(/[-:]/g, '').replace(/\..+/, '').replace('T', '_');
  const backupDir = `${abs}_backup_${stamp}`;
  cpSync(abs, backupDir, { recursive: true });
  return backupDir;
}

/** 恢复提示：同时给 POSIX 与 Windows 两条命令（gitlike 只给了 PowerShell）。 */
export function restoreGitDirHint(backupDir: string, repoRoot: string): string {
  return [
    '如需恢复原 git 历史，请执行：',
    `  cd ${repoRoot}`,
    '  # POSIX',
    `  rm -rf .git && cp -R ${backupDir} .git`,
    '  # Windows (PowerShell)',
    `  Remove-Item -Recurse -Force .git; Copy-Item -Recurse ${backupDir} .git`,
  ].join('\n');
}

/**
 * 把 mainBranch..HEAD 的每个提交重写成「幽灵」。
 * 返回被重写的提交数。
 */
export async function rewriteAsGhost(mainBranch: string, cwd?: string): Promise<number> {
  const rows = await commitsBetween(mainBranch, 'HEAD', 0, cwd);
  if (rows.length === 0) {
    throw new Error(`没有可重写的提交（HEAD 可能已经等于 ${mainBranch}）`);
  }

  const metaFile = writeGhostMetadata(rows);
  const scriptDir = mkdtempSync(join(tmpdir(), 'nx-nx-ghost-filter-'));
  const scriptPath = join(scriptDir, 'ghost-tree-filter.sh');
  writeFileSync(scriptPath, GHOST_TREE_FILTER, 'utf8');

  try {
    const r = await runGit(
      ['filter-branch', '--force', '--tree-filter', `bash ${scriptPath.replace(/\\/g, '/')}`, '--', `${mainBranch}..HEAD`],
      {
        cwd,
        env: {
          [ENV_META]: metaFile,
          [ENV_HEADER]: GHOST_REWRITE_HEADER,
          FILTER_BRANCH_SQUELCH_WARNING: '1',
        },
        timeoutMs: 600_000,
      }
    );
    if (r.code !== 0) {
      const detail = (r.stderr || r.stdout || '').trim();
      throw new Error(`filter-branch 失败: ${detail || `退出码 ${r.code}`}`);
    }
    return rows.length;
  } finally {
    rmSync(metaFile, { force: true });
    rmSync(scriptDir, { recursive: true, force: true });
  }
}

/** 收尾：删掉 rewrite.txt 并提交快照（末尾追加 2 个 commit）。 */
export async function finalizeSnapshot(
  keepUntracked: boolean,
  message: string,
  cwd?: string
): Promise<void> {
  const r = await runGit(['rm', '-f', GHOST_REWRITE_FILE], { cwd });
  // 文件本来就不存在时 rm 会失败——继续走 add -u 即可。
  void r;
  const addTracked = await runGit(['add', '-u', GHOST_REWRITE_FILE], { cwd });
  void addTracked;
  const remove = await runGit(
    ['commit', '--allow-empty', '-m', GHOST_REMOVE_FILE_MESSAGE],
    { cwd }
  );
  if (remove.code !== 0) {
    throw new Error(`创建「删除 rewrite.txt」commit 失败: ${(remove.stderr || remove.stdout).trim()}`);
  }
  const stage = await runGit(keepUntracked ? ['add', '-A'] : ['add', '-u'], { cwd });
  if (stage.code !== 0) {
    throw new Error(`暂存快照失败: ${(stage.stderr || stage.stdout).trim()}`);
  }
  const commit = await runGit(['commit', '--allow-empty', '-m', message], { cwd });
  if (commit.code !== 0) {
    throw new Error(`创建快照 commit 失败: ${(commit.stderr || commit.stdout).trim()}`);
  }
}

/**
 * 清理 filter-branch 留下的 refs/original/* 备份引用。
 *
 * 它们会挡住强推：远端的旧 hash 已经不在本地了，push 会被拒。
 */
export async function cleanupFilterBranchRefs(cwd?: string): Promise<string[]> {
  const r = await runGit(['for-each-ref', '--format=%(refname)', 'refs/original/'], { cwd });
  if (r.code !== 0) return [];
  const refs = r.stdout
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean);
  for (const ref of refs) {
    await runGit(['update-ref', '-d', ref], { cwd });
  }
  return refs;
}

export function ghostRewriteFileExists(root: string): boolean {
  return existsSync(join(root, GHOST_REWRITE_FILE));
}
